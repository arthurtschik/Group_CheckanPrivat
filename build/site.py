# ---------------------------------------------------------------- legal pages

def const(src, name):
    m = re.search(r"const " + name + r"=`(.*?)`;", src, re.S)
    if not m:
        raise SystemExit(f"{name} not found in {SRC}")
    text = m.group(1)
    if "${" in text or "`" in text:
        raise SystemExit(f"{name} contains template expressions - cannot be exported as static HTML")
    return text


def legal_pages():
    src = open(SRC, encoding="utf-8").read()
    for const_name, filename, title in (("PRIVACY_HTML", "datenschutz.html", "Datenschutzhinweis"),
                                        ("TERMS_HTML", "nutzungsbedingungen.html", "Nutzungsbedingungen")):
        body = const(src, const_name)
        body = re.sub(r"^<h2>(.*?)</h2>", r"<h1>\1</h1>", body, count=1)   # page title is the main heading
        body = "\n".join("    " + line for line in body.splitlines())
        path = os.path.join(OUT, filename)
        with open(path, "w", encoding="utf-8") as f:
            f.write(PAGE.format(title=title, content=body))
        print("wrote", os.path.relpath(path, ROOT))
    open(os.path.join(OUT, ".nojekyll"), "w").close()   # serve files as they are (no Jekyll processing)


# ---------------------------------------------------------------- release news
# Mirrors the parser in docs/assets/app.js (so the page looks the same whether baked in or rendered live).

STOP_HEADING = re.compile(r"^(Update|Signatur|Prüfsummen?|Hinweis|Was bisher\b.*)\s*$", re.I)
TOKEN = re.compile(r"(\*\*[^*]+\*\*|\*[^*\s][^*]*\*|`[^`]+`|\[[^\]]+\]\([^)\s]+\))")
esc = lambda s: html.escape(s, quote=True)


def rich(text):
    out = []
    for part in TOKEN.split(text):
        if not part:
            continue
        m = re.fullmatch(r"\[([^\]]+)\]\(([^)\s]+)\)", part)
        if re.fullmatch(r"\*\*[^*]+\*\*", part):
            out.append(f"<strong>{esc(part[2:-2])}</strong>")
        elif re.fullmatch(r"\*[^*\s][^*]*\*", part):
            out.append(f"<em>{esc(part[1:-1])}</em>")
        elif re.fullmatch(r"`[^`]+`", part):
            out.append(f"<code>{esc(part[1:-1])}</code>")
        elif m:
            if m.group(2).lower().startswith(OWNER.lower()):
                out.append(f'<a href="{esc(m.group(2))}" rel="noopener">{esc(m.group(1))}</a>')
            else:
                out.append(esc(m.group(1)))
        else:
            out.append(esc(part))
    return "".join(out)


def parse_news(md):
    items, cur, in_fence, first_heading = [], None, False, True
    for line in md[:20000].splitlines():
        if len(items) >= 80:
            break
        if re.match(r"^\s*```", line):
            in_fence, cur = not in_fence, None
            continue
        if in_fence:
            continue
        if re.match(r"^\s*-{3,}\s*$", line):
            break                                            # first separator ends the news
        if not line.strip():
            cur = None
            continue
        h = re.match(r"^#{1,4}\s+(.*)$", line)
        if h:
            cur = None
            text = h.group(1).strip()
            if STOP_HEADING.match(re.sub(r"^[^A-Za-zÄÖÜäöüß0-9]+", "", text)):
                break
            if first_heading:                                # main title is already in the summary
                first_heading = False
                continue
            cur = {"t": "h", "text": text}
            items.append(cur)
            cur = None
            continue
        b = re.match(r"^\s*[-*]\s+(.*)$", line)
        if b:
            cur = {"t": "li", "text": b.group(1).strip()}
            items.append(cur)
            continue
        q = re.sub(r"^\s*>\s?", "", line).strip()
        if not q:
            cur = None
            continue
        if cur and cur["t"] != "h":
            cur["text"] += " " + q                           # wrapped line belongs to the same paragraph/item
        else:
            cur = {"t": "p", "text": q}
            items.append(cur)
    return items


def render_news(items, version, url):
    parts, in_list = [], False
    for it in items:
        if it["t"] == "li":
            if not in_list:
                parts.append("<ul>")
                in_list = True
            parts.append(f"<li>{rich(it['text'])}</li>")
            continue
        if in_list:
            parts.append("</ul>")
            in_list = False
        parts.append(f'<p class="nh">{rich(it["text"])}</p>' if it["t"] == "h" else f"<p>{rich(it['text'])}</p>")
    if in_list:
        parts.append("</ul>")
    parts.append(f'<a class="more" href="{esc(url)}" rel="noopener">Alle Release-Notizen</a>')
    body = "\n      ".join(parts)
    return (f'<details class="news" id="news" data-version="{esc(version)}">\n'
            f'    <summary id="newsTitle">Was ist neu in {esc(version)}?</summary>\n'
            f'    <div class="news-body" id="newsBody">\n      {body}\n    </div>\n'
            f'  </details>')


def newest_local():
    best = None
    rel = os.path.join(OUT, "releases")
    for name in os.listdir(rel):
        m = re.fullmatch(r"v(\d+(?:\.\d+){0,3})\.md", name)
        if m:
            key = tuple(int(x) for x in m.group(1).split("."))
            if best is None or key > best[0]:
                best = (key, m.group(1), os.path.join(rel, name))
    if not best:
        raise SystemExit("no docs/releases/v*.md found")
    return best[1], open(best[2], encoding="utf-8").read()


def from_github():
    try:
        raw = subprocess.run(["gh", "api", f"repos/{REPO}/releases/latest"], check=True, capture_output=True, text=True, timeout=60).stdout
        rel = json.loads(raw)
    except Exception as e:                                   # no gh, no network, no release yet ...
        raise SystemExit(f"could not read the GitHub release: {e}")
    tag = str(rel.get("tag_name", ""))
    if not re.fullmatch(r"v?\d+(?:\.\d+){0,3}", tag):
        raise SystemExit(f"unexpected tag name: {tag!r}")
    return tag.lstrip("vV"), rel.get("body") or ""


def bake_news(use_github):
    version, md = from_github() if use_github else newest_local()
    items = parse_news(md)
    if not items:
        raise SystemExit(f"release notes of v{version} contain no news section - nothing to show")
    url = f"{OWNER}Group_Checkan/releases/tag/v{version}"
    path = os.path.join(OUT, "index.html")
    page = open(path, encoding="utf-8").read()
    block = render_news(items, version, url)
    page, n1 = re.subn(r"(?s)<!--news:start-->.*?<!--news:end-->", lambda m: f"<!--news:start-->\n  {block}\n  <!--news:end-->", page)
    page, n2 = re.subn(r'(<p id="meta" class="meta" data-baked="1">).*?(</p>)', lambda m: f"{m.group(1)}Version {esc(version)}{m.group(2)}", page)
    if n1 != 1 or n2 != 1:
        raise SystemExit("markers not found in docs/index.html (news block or meta line)")
    with open(path, "w", encoding="utf-8") as f:
        f.write(page)
    print(f"baked 'Was ist neu in {version}?' ({len(items)} Einträge, Quelle: {'GitHub' if use_github else 'docs/releases/v' + version + '.md'}) into docs/index.html")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--github", action="store_true", help="take the release notes from the published GitHub release")
    args = ap.parse_args()
    legal_pages()
    bake_news(args.github)


if __name__ == "__main__":
    main()
